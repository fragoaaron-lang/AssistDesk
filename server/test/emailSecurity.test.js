const test = require('node:test');
const assert = require('node:assert/strict');
const { escapeHtml, generateVerificationCode, buildAccountAppealEmail } = require('../utils/email');

test('email HTML escapes untrusted values before template interpolation', () => {
  assert.equal(escapeHtml(`<img src=x onerror="alert('x')"> &`), '&lt;img src=x onerror=&quot;alert(&#39;x&#39;)&quot;&gt; &amp;');
});

test('email verification codes are fixed-width numeric values generated by crypto.randomInt', () => {
  for (let i = 0; i < 25; i += 1) assert.match(generateVerificationCode(), /^\d{8}$/);
});

test('termination appeal emails escape user-provided fields and preserve plain-text line breaks', () => {
  const email = buildAccountAppealEmail({
    userName: '<img src=x>',
    userEmail: 'person@example.edu',
    role: 'student',
    departmentName: 'Computer Studies',
    terminationReason: 'Policy <violation>',
    appealMessage: 'Please review.\nI believe this was a mistake.',
  });

  assert.equal(email.subject, 'AssistDesk account termination appeal');
  assert.match(email.html, /&lt;img src=x&gt;/);
  assert.match(email.html, /Policy &lt;violation&gt;/);
  assert.match(email.html, /Please review\.<br>I believe this was a mistake\./);
  assert.doesNotMatch(email.html, /<img src=x>/);
});
